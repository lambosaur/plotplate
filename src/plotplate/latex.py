r"""Generate the LaTeX that places panels exactly where the layout says.

The snippet uses only ``graphicx`` and the kernel ``picture`` environment with
``\unitlength=1mm``. Panels are included *without* width/height options, i.e. at scale
1.0, so fonts keep their true point size and a wrongly-sized panel is visible rather
than silently stretched.

Usage in the manuscript::

    \begin{figure}
      \centering
      \input{figures/fig1/fig1.tex}
      \caption{...}
    \end{figure}

``--panel-refs`` adds one optional block, for manuscripts that reference a single panel: it
defines ``\plotplatePanelLabels``, which turns the figure's letters into labels
(``\ref{fig:7a}`` prints ``7a``) and replaces ``subfigure``'s sub-captions. It is off by
default, because it is a page of ``\makeatletter`` in a file whose point is to be obvious.

Panel letters use ``\plotplatePanelLabel``, defined with ``\providecommand`` from the layout's
``panel_label`` style (size, weight, and ``latex_font`` for the font commands): define your own
version in the preamble to override it entirely.

They are stamped with ``\put`` at the millimetre the layout gives, over the panel's own margin,
so they take no space of their own -- unlike ``subcaption``/``subfigure``, which add a line
under each panel and would make the assembled figure taller than the layout says.
"""

from __future__ import annotations

import shutil
from pathlib import Path, PurePosixPath

from .layout import Layout
from .style import label_text


def _fmt(value: float) -> str:
    return f"{value:.2f}"


def figure_tex(
    layout: Layout,
    graphics_prefix: str = "panels/",
    labels: bool = True,
    panel_refs: bool = False,
) -> str:
    r"""LaTeX source of the figure body (no ``figure`` environment, no caption).

    What comes out is meant to be read by whoever opens it in Overleaf: a picture box of the
    figure's size, one ``\includegraphics`` per panel, one ``\makebox`` per letter. The only
    definition is ``\plotplatePanelLabel``, which sets the letters' font and can be redefined in
    the preamble. ``panel_refs`` adds the machinery for referencing a single panel, which is a
    page of ``\makeatletter`` and is therefore left out unless it is asked for.
    """
    label = layout.style["panel_label"]
    weight = r"\bfseries" if label["weight"] == "bold" else ""
    size = float(label["size"])
    family = str(label.get("latex_font") or r"\sffamily")
    source = layout.path.name if layout.path else "a layout mapping"
    lines = [
        f"% The panels of {layout.name}, placed. Generated by plotplate from {source}:",
        "% `plotplate build` rewrites this file, so put the caption, the label and the figure",
        f"% placement in {layout.name}-figure.tex (or in the manuscript), not here.",
        "% Requires \\usepackage{graphicx}. Panels are included at natural size (scale 1.0).",
        "\\providecommand{\\plotplatePanelLabel}[1]{{\\fontsize{"
        + f"{size:g}pt"
        + "}{"
        + f"{size:g}pt"
        + "}\\selectfont"
        + family
        + weight
        + " #1}}%",
        "{\\setlength{\\unitlength}{1mm}%",
        f"\\begin{{picture}}({_fmt(layout.width)},{_fmt(layout.height)})%",
    ]
    for name, spec in layout.panels.items():
        path = PurePosixPath(graphics_prefix) / f"{name}.pdf" if graphics_prefix else f"{name}.pdf"
        # picture coordinates: origin bottom-left; an image's reference point is its bottom-left.
        lines.append(
            f"\\put({_fmt(spec.box.x)},{_fmt(layout.height - spec.box.bottom)})"
            f"{{\\includegraphics{{{path}}}}}% panel {name}"
        )
    if labels:
        for spec in layout.panels.values():
            if not spec.label:
                continue
            x = spec.box.x + spec.label_offset[0]
            y = layout.height - (spec.box.y + spec.label_offset[1])
            text = label_text(layout.style, spec.label)
            lines.append(
                f"\\put({_fmt(x)},{_fmt(y)})"
                f"{{\\makebox(0,0)[lt]{{\\plotplatePanelLabel{{{text}}}}}}}%"
            )
    lines.append("\\end{picture}}%")
    if labels and panel_refs:
        letters = [spec.label for spec in layout.panels.values() if spec.label]
        lines += _panel_reference_macros(letters)
    lines.append("")
    return "\n".join(lines)


def _panel_reference_macros(letters: list[str]) -> list[str]:
    r"""LaTeX that lets the manuscript reference one panel: ``\ref{fig:7a}`` prints ``7a``.

    The figure's number is only final after ``\caption``, so the labels cannot be written here;
    what is written is the list of letters and one macro that turns it into labels, which the
    author calls after the caption::

        \caption{...}\label{fig:7}
        \plotplatePanelLabels{fig:7}        % defines fig:7a, fig:7b, ...
        \plotplatePanelLabels[:panel-]{fig7} % ... or fig7:panel-a, for other conventions

    Everything is defined globally with ``\gdef``: the file is ``\input`` inside a ``figure``
    environment, and a definition made there would be gone by the next figure. The macro itself
    is defined once (a second figure only replaces the list), and never over one the author
    defined. Where ``cleveref`` is loaded, its own label is set too, so ``\cref`` prints
    "fig. 7a" rather than dropping the letter.
    """
    if not letters:
        return []
    return [
        "% Panel cross-references. After \\caption, call \\plotplatePanelLabels{<figure label>}%",
        "% to define <figure label>a, <figure label>b, ...; the optional argument inserts a%",
        "% separator: \\plotplatePanelLabels[:panel-]{fig7} defines fig7:panel-a.%",
        "\\makeatletter%",
        "\\gdef\\plotplate@panels{" + ",".join(letters) + "}%",
        "\\@ifundefined{plotplatePanelLabels}{%",
        "  \\gdef\\plotplatePanelLabels{%",
        "    \\@ifnextchar[\\plotplate@panel@labels{\\plotplate@panel@labels[]}}%",
        "  \\gdef\\plotplate@panel@labels[#1]#2{%",
        "    \\@for\\plotplate@p:=\\plotplate@panels\\do{%",
        "      \\begingroup%",
        "        \\edef\\@currentlabel{\\thefigure\\plotplate@p}%",
        "        \\@ifundefined{cref@currentlabel}{}{%",
        "          \\protected@edef\\cref@currentlabel{%",
        "            [figure][\\arabic{figure}][]\\thefigure\\plotplate@p}}%",
        "        \\label{#2#1\\plotplate@p}%",
        "      \\endgroup}}%",
        "}{}%",
        "\\makeatother%",
    ]


def write_figure_tex(
    layout: Layout,
    out: str | Path | None = None,
    graphics_prefix: str = "panels/",
    labels: bool = True,
    panel_refs: bool = False,
) -> Path:
    """Write the snippet to ``out`` (default ``<layout dir>/<name>.tex``)."""
    target = Path(out) if out is not None else layout.base_dir / f"{layout.name}.tex"
    target.write_text(figure_tex(layout, graphics_prefix, labels, panel_refs), encoding="utf-8")
    return target


def write_figure_scaffold(
    layout: Layout,
    out: str | Path | None = None,
    graphics_prefix: str = "panels/",
    force: bool = False,
) -> Path:
    r"""Write ``<name>-figure.tex``: the figure as the manuscript sees it, for the author to edit.

    This is the half of the output that is *not* generated material. It holds the ``figure``
    environment, the placement, the caption and the label -- the parts that belong to the text --
    and it includes the generated file, which holds the panels. The manuscript then needs one
    line per figure::

        \input{figures/figure_7/figure_7-figure.tex}

    It is written once and never again: ``plotplate build`` rewrites the panels beside it and
    leaves this file alone, so a caption written here survives every rebuild. ``force`` writes a
    fresh one, which is how to get the scaffold back after deleting it.
    """
    target = Path(out) if out is not None else layout.base_dir / f"{layout.name}-figure.tex"
    if target.exists() and not force:
        return target
    body = f"{graphics_prefix}{layout.name}.tex" if graphics_prefix else f"{layout.name}.tex"
    target.write_text(
        "\n".join(
            [
                f"% {layout.name}: this file is yours. Edit the caption, the label, the",
                "% placement ([t], [h!], ...), or wrap it in a starred figure* for a wide one.",
                "% plotplate never overwrites it; it rewrites the panels in the file included below.",
                "\\begin{figure}[tbp]",
                "  \\centering",
                f"  \\input{{{body}}}%",
                "  \\caption{...}",
                f"  \\label{{fig:{layout.name}}}",
                "\\end{figure}",
                "",
            ]
        ),
        encoding="utf-8",
    )
    return target


def bundle(
    layout: Layout,
    out_dir: str | Path,
    graphics_prefix: str | None = None,
    panel_refs: bool = False,
) -> Path:
    r"""Copy ``<name>.tex`` and the panel PDFs into ``out_dir`` for upload to Overleaf.

    The composed figure (``preview.pdf``) is copied too, as ``<name>.pdf``, when it exists. It
    is not what the manuscript includes -- ``\input{<name>.tex}`` places the panels, which is
    what keeps them at scale 1.0 and the letters where the layout puts them -- but it is the
    one file to look at, to send to a co-author, and to hand-finish in a drawing program when a
    figure needs a last touch that no layout can express. Including that file instead is then
    one line (see ``docs/workflow.md``).

    Args:
        layout: the figure layout.
        out_dir: destination folder (created). Upload its content as-is.
        graphics_prefix: path of the panels as seen from the Overleaf project root,
            default ``figures/<name>/``, matching an upload of ``out_dir`` there.
        panel_refs: also write the optional block that lets the manuscript reference one panel.
    """
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    prefix = graphics_prefix if graphics_prefix is not None else f"figures/{layout.name}/"
    missing = []
    for name in layout.panels:
        pdf = layout.panels_dir / f"{name}.pdf"
        if pdf.exists():
            shutil.copy2(pdf, out_dir / pdf.name)
        else:
            missing.append(name)
    if missing:
        raise FileNotFoundError(f"Panels without PDF: {missing}; run their notebooks first")
    composed = layout.base_dir / "preview.pdf"
    if composed.exists():
        shutil.copy2(composed, out_dir / f"{layout.name}.pdf")
    write_figure_scaffold(
        layout, out_dir / f"{layout.name}-figure.tex", graphics_prefix=prefix, force=True
    )
    return write_figure_tex(
        layout, out_dir / f"{layout.name}.tex", graphics_prefix=prefix, panel_refs=panel_refs
    )


def standalone_document(layout: Layout, graphics_prefix: str = "panels/", labels: bool = True) -> str:
    """A compilable document whose page is exactly the figure (``standalone`` class)."""
    return "\n".join(
        [
            "\\documentclass[border=0pt]{standalone}",
            "\\usepackage{graphicx}",
            "\\begin{document}",
            figure_tex(layout, graphics_prefix, labels),
            "\\end{document}",
            "",
        ]
    )
